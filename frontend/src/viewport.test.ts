import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

/**
 * §42 — две ловушки телефона, которых не видит ни один замер.
 *
 * Обе всплыли одной жалобой с живого телефона: «шахматка двигается в разные
 * стороны, да и вообще все окна в приложении». До этого приложение прошло
 * сплошной «глубокий анализ» на 390px, `audit-mobile` не находил ни одного
 * переполнения, и пункт «проверить на живом телефоне» так и висел открытым —
 * потому что **headless-браузер физически не может это воспроизвести**.
 *
 * Поэтому здесь не замер, а сторож на исходник: он ловит возврат обеих причин
 * при следующей правке стилей, а не через два месяца по второй жалобе.
 */
// Читается с диска, а не импортируется. Vitest подменяет импорт CSS заглушкой,
// и `?raw` тоже отдаёт пустую строку — сторож молча проходил бы всегда, что
// хуже, чем его отсутствие. Ради этого в tsconfig.app.json добавлены типы node.
const css = readFileSync(join(process.cwd(), 'src', 'index.css'), 'utf8')
const lines = css.split(/\r?\n/)

describe('§42 высота считается от того, что видно', () => {
  it('у каждого правила на vh есть двойник на svh', () => {
    // `100vh` на телефоне — это высота при **убранной** адресной строке, то
    // есть больше видимого на 60–110px. Всё, что размечено в `vh`, оказывается
    // выше экрана, и страница ползает даже там, где содержимое помещается.
    // `svh` — высота при видимой строке: не меняется при прокрутке (в отличие
    // от `dvh`) и гарантированно не больше того, что видно.
    const offenders: string[] = []

    lines.forEach((line: string, index: number) => {
      const code = line.split('/*')[0]
      // Только объявления: комментарии обсуждают `vh` свободно и по делу.
      if (!/^\s*[\w-]+\s*:/.test(code)) return
      if (!/\d\s*vh\b/.test(code)) return

      const property = code.trim().split(':')[0].trim()
      // Запасной вариант идёт первым, замена — следующей строкой, чтобы
      // браузер без поддержки `svh` взял то, что понимает.
      const next = lines[index + 1] ?? ''
      const paired =
        // Без `\b` перед `svh`: между `0` и `s` в «100svh» границы слова нет,
        // и сторож ловил бы сам себя — первым, на чём он и попался.
        new RegExp(`^\\s*${property}\\s*:`).test(next) && /\dsvh\b/.test(next)

      if (!paired) offenders.push(`${index + 1}: ${line.trim()}`)
    })

    expect(offenders).toEqual([])
  })

  it('и таких правил всё ещё столько, сколько мы починили', () => {
    // Ловит противоположную ошибку: не «вернули vh», а «выкинули запасной
    // вариант», после чего старый браузер получит высоту в никуда.
    const pairs = lines.filter((line: string) => /\dsvh\b/.test(line.split('/*')[0] ?? ''))
    expect(pairs.length).toBeGreaterThanOrEqual(5)
  })
})

describe('§42 поля не заставляют iPhone увеличивать страницу', () => {
  it('на телефоне у полей ввода 16px', () => {
    // Safari на iPhone масштабирует страницу, как только фокус попадает в поле
    // мельче 16px, и обратно не возвращает. После этого приложение ездит
    // пальцем во все стороны, потому что увеличенная страница больше экрана —
    // а каждый диалог здесь это форма.
    const phoneBlock = css.slice(css.indexOf('@media (max-width: 640px)'))
    const rule = phoneBlock.match(
      /input,\s*select,\s*textarea\s*\{[^}]*font-size:\s*(\d+)px/
    )

    expect(rule, 'нет правила на размер шрифта у полей в телефонном блоке').toBeTruthy()
    expect(Number(rule![1])).toBeGreaterThanOrEqual(16)
  })
})
